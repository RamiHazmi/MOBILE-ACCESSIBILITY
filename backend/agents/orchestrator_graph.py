# NODE 4f — memory_node
# Answers "where did I last see my X?" from the SQLite memory DB.
# ═══════════════════════════════════════════════════════════════

def memory_node(state: GlassesState) -> GlassesState:
    lang   = state.get("language", "en")
    target = (state.get("memory_target") or "").strip()

    if not target:
        # No target extracted — ask the user to be more specific
        _no_target = {
            "en": "What object are you looking for? Please say its name.",
            "fr": "Quel objet cherchez-vous ? Dites son nom.",
            "ar": "ما الشيء الذي تبحث عنه؟ قل اسمه.",
            "tn": "شنو الحاجة اللي تحب تلقاها؟ قول اسمها.",
        }
        return {**state, "speak": _no_target.get(lang, _no_target["en"])}

    record = get_last_sighting(target, state.get("user_id") or "")

    if not record:
        speak = t("memory_never_seen", lang, target=target)
        return {**state, "speak": speak}

    # Build relative time string
    time_str = relative_time(record["saved_at"], lang)

    # Try to get a human-readable location
    lat = record.get("gps_lat")
    lng = record.get("gps_lng")
    location_str = None
    if lat is not None and lng is not None:
        try:
            location_str = reverse_geocode(lat, lng)
        except Exception:
            pass

    if location_str:
        speak = t("memory_last_seen", lang,
                  target=target,
                  time=time_str,
                  location=location_str)
    else:
        scene = record.get("scene_description") or ""
        # Build a natural location description from the scene
        if scene:
            location_desc = scene
        else:
            location_desc = {
                "en": "an unknown location",
                "fr": "un endroit inconnu",
                "ar": "مكان غير معروف",
                "tn": "بلاصة ما نعرفهاش",
            }.get(lang, "an unknown location")
        speak = t("memory_last_seen_no_location", lang,
                  target=target,
                  time=time_str,
                  scene=location_desc)

    print(f"[memory] query='{target}' → {time_str}, loc={location_str}")
    return {**state, "speak": speak}


