# NODE 5 — action_speak
# ═══════════════════════════════════════════════════════════════

def action_speak(state: GlassesState, *, action: ActionAgent) -> GlassesState:
    speak     = state.get("speak", "")
    interrupt = state.get("interrupt", False)
    language  = state.get("language", "en")

    # ── "I can see you" injection for non-describe nodes ────────
    # describe() already appends person sentences for DESCRIBE mode.
    # For every other mode (navigate, find_object, danger, etc.) we
    # inject it here so the user hears it regardless of what they asked.
    _mode = (state.get("mode") or "").upper()
    if _mode not in {"DESCRIBE", "IDLE", ""}:
        _scene = state.get("scene") or {}
        for _ip in (_scene.get("identified_persons") or []):
            if not _ip.get("match") or _ip.get("confidence") == "low":
                continue
            _rel = (_ip.get("relationship") or "").strip().lower()
            if _rel not in {"self", "me", "myself"}:
                continue
            _name = _ip["match"]
            _greeting = {
                "en": f"I can see you, {_name}.",
                "fr": f"Je vous vois, {_name}.",
                "ar": f"أراك يا {_name}.",
                "tn": f"نشوفك يا {_name}.",
            }.get(language, f"I can see you, {_name}.")
            speak = (_greeting + " " + speak).strip() if speak else _greeting
            break  # only announce once even if multiple matches

    if speak:
        if interrupt:
            action.speak_danger(speak)
        else:
            action.speak_normal(speak, lang=language)
        tag = "🚨 " if interrupt else ""
        print(f"[action_speak] {tag}({language}) {speak}")
    return state


