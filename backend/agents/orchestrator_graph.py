# NODE 4i — delete_location_node
# "Delete this location" / "Forget home" → removes from DB.
# ═══════════════════════════════════════════════════════════════

def delete_location_node(state: GlassesState) -> GlassesState:
    from memory_service import delete_named_location, get_named_location
    from memory_service import reverse_geocode, get_all_named_locations
    lang     = state.get("language", "en")
    entities = state.get("entities", [])
    label    = (entities[0] if entities else "").strip().lower()
    lat      = state.get("user_lat")
    lng      = state.get("user_lng")
    user_id  = state.get("user_id") or ""

    _deleted = {
        "en": "Done. I deleted the location {label}.",
        "fr": "Fait. J'ai supprimé l'endroit {label}.",
        "ar": "تم. حذفت المكان {label}.",
        "tn": "صار. مسحت البلاصة {label}.",
    }
    _not_found = {
        "en": "I don't have a saved location called {label}.",
        "fr": "Je n'ai pas d'endroit sauvegardé appelé {label}.",
        "ar": "ليس لدي مكان محفوظ باسم {label}.",
        "tn": "ما عنديش بلاصة محفوظة باسم {label}.",
    }
    _deleted_current = {
        "en": "Done. I deleted the current location.",
        "fr": "Fait. J'ai supprimé l'endroit actuel.",
        "ar": "تم. حذفت الموقع الحالي.",
        "tn": "صار. مسحت البلاصة الحالية.",
    }

    # If no label given, try to find by current GPS
    if not label and lat is not None and lng is not None:
        try:
            rows = get_all_named_locations(user_id)
            best_label = None
            best_dist  = float("inf")
            for row in rows:
                dlat = (row["gps_lat"] - lat) ** 2
                dlng = (row["gps_lng"] - lng) ** 2
                d = (dlat + dlng) ** 0.5
                if d < best_dist:
                    best_dist  = d
                    best_label = row["label"]
            if best_label and best_dist < 0.01:  # ~1 km
                delete_named_location(best_label, user_id)
                return {**state, "speak": _deleted_current.get(lang, _deleted_current["en"])}
        except Exception:
            pass
        return {**state, "speak": _not_found.get(lang, _not_found["en"]).format(label="this location")}

    if not label:
        return {**state, "speak": _not_found.get(lang, _not_found["en"]).format(label="that")}

    deleted = delete_named_location(label, user_id)
    if deleted:
        speak = _deleted.get(lang, _deleted["en"]).format(label=label)
    else:
        speak = _not_found.get(lang, _not_found["en"]).format(label=label)

    return {**state, "speak": speak}


