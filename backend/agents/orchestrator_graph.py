"""
orchestrator_graph.py — v4 (LangGraph multi-agent with confirmation)
─────────────────────────────────────────────────────────────────────
Pipeline:

   ┌─────────────┐
   │ perception  │  (only when a frame is provided)
   └──────┬──────┘
          ↓
   after_perception ─── danger      → danger_node      → action_speak → END
                  ├──── awaiting_cf → confirm_node     → action_speak → END
                  ├──── needs_clar  → clarify_node     → action_speak → END
                  └──── route_intent
                            │
                            ├── env_action+find → find_object   → action_speak → END
                            ├── env_action      → describe      → action_speak → END
                            ├── navigate        → navigate      → action_speak → END
                            └── query           → query         → action_speak → END

KEY DIFFERENCES vs v3:
  • New `confirm_node` reads the pending question generated by
    DialogueAgent and speaks it BEFORE any camera/navigation
    screen opens.  The user must answer "yes" to proceed.
  • Vision uses free OpenRouter models with fallback
    (gemma-3-27b → nemotron-nano-12b VL).
  • Navigation uses free Overpass + Nominatim + OSRM.
  • Find-object now relies on PerceptionAgent's temporal consensus
    so transient bad frames don't trigger premature "I cannot see".
"""

