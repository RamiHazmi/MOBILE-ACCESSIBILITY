# ═══════════════════════════════════════════════════════════════
# STATE
# ═══════════════════════════════════════════════════════════════

class GlassesState(TypedDict, total=False):
    intent:                 str
    entities:               list[str]
    language:               str
    transcription:          str
    frame_b64:              Optional[str]
    needs_clarification:    bool
    clarification_question: str
    awaiting_confirmation:  bool

    user_lat: Optional[float]
    user_lng: Optional[float]

    scene:        Optional[dict]
    danger_level: str

    mode:        str
    find_target: Optional[str]
    found:       Optional[bool]
    direction:   Optional[str]

    nav_destination: Optional[str]
    nav_mode:        Optional[str]
    nav_update:      Optional[dict]

    speak:        str
    interrupt:    bool
    rate_limited: bool

    # Emotion detection results — populated by perception_node only
    # when mode == DESCRIBE.  Each entry: {label, confidence,
    # position, bbox}.  Empty list if EmotionAgent disabled or no
    # faces detected.
    emotions:     list

    # Memory query target — set by route_intent when intent==memory_query
    memory_target: Optional[str]

    # Device UUID forwarded from X-User-ID header — scopes all DB reads/writes
    user_id: Optional[str]

    # Set to True by main.py when user confirmed a duplicate-replace prompt,
    # so save_location_node skips the duplicate check and overwrites directly.
    _force_replace: Optional[bool]


# ═══════════════════════════════════════════════════════════════
# NODE 1 — perception (only when frame exists)
# ═══════════════════════════════════════════════════════════════

def perception_node(state: GlassesState, *,
                    perception: PerceptionAgent,
                    emotion=None) -> GlassesState:
    frame_b64   = state.get("frame_b64")
    find_target = state.get("find_target")
    mode        = state.get("mode", "")

    if not frame_b64:
        return {**state, "scene": None, "danger_level": "LOW",
                "rate_limited": False, "emotions": []}

    rate_limited = False
    emotions: list = []
    try:
        raw_bytes = base64.b64decode(frame_b64)
        arr       = np.frombuffer(raw_bytes, dtype=np.uint8)
        frame     = cv2.imdecode(arr, cv2.IMREAD_COLOR)
        if frame is None:
            print("[perception] imdecode None")
            return {**state, "scene": None, "danger_level": "LOW",
                    "rate_limited": False, "emotions": []}

        frame_small = cv2.resize(frame, (perception.width, perception.height))
        img_b64     = perception.encode(frame_small)
        raw         = perception.ask(img_b64, find_target=find_target)
        if raw is None:
            # All VLM models exhausted — tell the frontend to back off
            rate_limited = True
            print("[perception] all models exhausted — rate_limited=True")
        scene = perception.parse_output(raw, find_target=find_target) if raw else None
        if scene and find_target:
            scene = perception.apply_consensus(scene, find_target)

        # Emotion inference — run when the user asked to describe the
        # scene (intent == env_action with no find-type keywords).
        # NOTE: `mode` is still "IDLE" here because route_intent hasn't
        # run yet — we must infer describe intent from `intent` +
        # transcription instead of relying on mode == "DESCRIBE".
        _transcript_lc = state.get("transcription", "").lower()
        _find_kws = ["find", "where is", "where's", "look for",
                     "search", "locate", "lost"]
        _is_describe_intent = (
            state.get("intent") == "env_action"
            and not any(kw in _transcript_lc for kw in _find_kws)
        )
        # Also allow explicit DESCRIBE mode (used by the /vision endpoint)
        _is_describe_intent = _is_describe_intent or mode == "DESCRIBE"

        if _is_describe_intent:
            if emotion is None:
                print("[emotion] skipped — no agent injected")
            elif not emotion.ready:
                print("[emotion] skipped — agent not ready "
                      "(check model file + tensorflow install)")
            else:
                try:
                    emotions = emotion.detect(frame)
                    if emotions:
                        print(f"[emotion] detected: "
                              f"{[(e['label'], round(e['confidence'], 2), e['position']) for e in emotions]}")
                    else:
                        print("[emotion] no faces detected in this frame")
                except Exception as e:
                    print(f"[emotion] error (non-fatal): {e}")
                    emotions = []

        # ── Personal person identification (all modes) ───────────
        # Runs whenever the scene contains a person-like object and the
        # user has saved contacts (including themselves with rel="self").
        _person_labels = frozenset({
            "person", "man", "woman", "child", "human", "face", "people",
            "boy", "girl", "figure",
        })
        _scene_objs = (scene.get("objects", []) if scene else [])
        _has_person = any(
            any(pl in o.get("label", "").lower() for pl in _person_labels)
            for o in _scene_objs
        )
        if _has_person and scene is not None:
            _uid = state.get("user_id") or ""
            if _uid:
                try:
                    from memory_service import get_all_personal_persons
                    _saved = get_all_personal_persons(_uid)
                    if _saved:
                        _pid = perception.ask_person_id(img_b64, _saved)
                        if _pid and _pid.get("match"):
                            scene["identified_persons"] = [_pid]
                            print(f"[person_id] {_pid['match']} "
                                  f"conf={_pid['confidence']} "
                                  f"pos={_pid['position']}")
                except Exception as _pe:
                    print(f"[person_id] non-fatal: {_pe}")

    except Exception as e:
        print(f"[perception] error: {e}")
        scene = None

    danger_level = scene.get("danger_level", "LOW") if scene else "LOW"
    return {**state, "scene": scene, "danger_level": danger_level,
            "rate_limited": rate_limited, "emotions": emotions}


# ═══════════════════════════════════════════════════════════════
# CONDITIONAL EDGE
# ═══════════════════════════════════════════════════════════════

def after_perception(state: GlassesState) -> Literal[
    "danger_node", "confirm_node", "clarify_node", "route_intent"
]:
    scene = state.get("scene") or {}
    is_dangerous = scene.get("is_dangerous")
    find_target  = state.get("find_target")
    mode         = state.get("mode")

    # DESCRIBE mode: the user explicitly asked "describe what's around
    # me" — they want a description, not a danger alert about their own
    # living room.  Suppress the danger path entirely.  Danger is for
    # the navigation flow, not for static scene description.
    if is_dangerous and mode == "DESCRIBE":
        scene["is_dangerous"]   = False
        scene["danger_level"]   = "LOW"
        scene["danger_message"] = ""
        return "route_intent"

    # If we're actively in FIND mode and the "danger" the VLM is
    # flagging is actually the object the user asked us to find,
    # suppress the danger path so the user hears "I found your X"
    # instead of a hazard warning.
    if is_dangerous and find_target and mode in ("FIND_OBJECT", "FIND"):
        target_lc = find_target.lower()
        objects   = scene.get("objects", []) or []
        threats_match_target = any(
            target_lc in (str(o.get("label", "")).lower()) for o in objects
        )
        if threats_match_target or scene.get("target_found"):
            # The "hazard" is what the user is looking for — not a hazard.
            scene["is_dangerous"]    = False
            scene["danger_level"]    = "LOW"
            scene["danger_message"]  = ""
            scene["consensus_state"] = "FOUND"
            return "route_intent"

    if is_dangerous:
        return "danger_node"
    if state.get("awaiting_confirmation") and state.get("clarification_question"):
        return "confirm_node"
    if state.get("needs_clarification") and state.get("clarification_question"):
        return "clarify_node"
    return "route_intent"


# ═══════════════════════════════════════════════════════════════
# NODE 2 — danger / confirm / clarify
# ═══════════════════════════════════════════════════════════════

def _build_localized_danger(scene: dict, lang: str) -> str:
    """Compose a danger sentence in the user's language from the
    structured scene fields, instead of trusting the VLM's English."""
    cmd = (scene.get("navigation_command") or "GO_FORWARD").upper()
    cmd_phrase = {
        "STOP":       t("danger_stop", lang),
        "MOVE_LEFT":  t("danger_move_left", lang),
        "MOVE_RIGHT": t("danger_move_right", lang),
        "WAIT":       t("danger_wait", lang),
        "GO_FORWARD": t("danger_caution_ahead", lang),
    }.get(cmd, t("danger_caution_ahead", lang))

    # Add up to 2 nearest threat objects with position/distance
    threat_lines = []
    for obj in (scene.get("objects") or []):
        if not obj.get("threat"):
            continue
        if obj.get("distance") not in {"close", "near", "medium"}:
            continue
        line = t("danger_object_position", lang,
                 label=obj.get("label", ""),
                 dist=distance_phrase(obj.get("distance", "near"), lang),
                 position=position_word(obj.get("position", "center"), lang))
        threat_lines.append(line)
        if len(threat_lines) >= 2:
            break

    if threat_lines:
        return cmd_phrase + " " + " ".join(threat_lines)
    return cmd_phrase


def danger_node(state: GlassesState) -> GlassesState:
    scene = state.get("scene") or {}
    lang  = state.get("language", "en")

    # For English the PerceptionAgent's pre-built message is fine.
    # For other languages, compose locally from structured fields so
    # the user actually hears their own language.
    if lang == "en":
        message = (scene.get("danger_message")
                   or scene.get("guidance")
                   or t("danger_caution_ahead", lang))
    else:
        message = _build_localized_danger(scene, lang)

    print(f"[danger] 🚨 ({lang}) {message}")
    return {**state, "speak": message, "interrupt": True}


def confirm_node(state: GlassesState) -> GlassesState:
    """Speak the 'Did you mean X?' question and pause the pipeline."""
    q = state.get("clarification_question", "")
    print(f"[confirm] ❓ {q}")
    return {**state, "speak": q, "interrupt": False, "mode": "AWAIT_CONFIRM"}


def clarify_node(state: GlassesState) -> GlassesState:
    q = state.get("clarification_question", "")
    print(f"[clarify] ❓ {q}")
    return {**state, "speak": q, "interrupt": False, "mode": "IDLE"}


# ═══════════════════════════════════════════════════════════════
# NODE 3 — route_intent
# ═══════════════════════════════════════════════════════════════

def route_intent(state: GlassesState) -> GlassesState:
    intent     = state.get("intent", "unknown")
    entities   = state.get("entities", [])
    transcript = state.get("transcription", "").lower()

    mode        = "IDLE"
    find_target = state.get("find_target")

    def _entity_str(e) -> str:
        """Safely extract a plain string from an entity that may be a
        string or a legacy dict like {'type': 'object', 'value': 'phone'}."""
        if isinstance(e, str):
            return e
        if isinstance(e, dict):
            return str(e.get("value") or e.get("target") or "")
        return str(e)

    if intent == "env_action":
        find_kws = ["find", "where is", "where's", "look for", "search",
                    "locate", "lost", "فين", "دور", "شوفلي", "لقّيلي"]
        if any(k in transcript for k in find_kws) or entities:
            mode        = "FIND_OBJECT"
            find_target = _entity_str(entities[0]) if entities else "object"
        else:
            mode = "DESCRIBE"
    elif intent == "navigate":
        mode = "NAVIGATE"
    elif intent == "query":
        mode = "QUERY"
    elif intent == "read_handwriting":
        mode = "READ_HANDWRITING"
    elif intent == "memory_query":
        mode = "MEMORY_QUERY"
    elif intent == "name_query":
        mode = "NAME_QUERY"
    elif intent == "save_location":
        mode = "SAVE_LOCATION"
    elif intent == "delete_location":
        mode = "DELETE_LOCATION"
    elif intent == "save_object":
        mode = "SAVE_OBJECT"
    elif intent == "save_person":
        mode = "SAVE_PERSON"

    # Enhance find_target with personal object description if saved
    if mode == "FIND_OBJECT" and find_target:
        try:
            _pobj = get_personal_object(find_target, state.get("user_id") or "")
            if _pobj and _pobj.get("description"):
                find_target = f"{find_target} — looks like: {_pobj['description']}"
        except Exception:
            pass

    memory_target = _entity_str(entities[0]) if (intent == "memory_query" and entities) else state.get("memory_target")

    return {**state, "mode": mode, "find_target": find_target, "memory_target": memory_target}


def after_route(state: GlassesState) -> Literal[
    "find_object", "describe", "navigate", "query",
    "read_handwriting", "memory_node", "name_node",
    "save_location_node", "delete_location_node",
    "save_object_node", "save_person_node", "action_speak"
]:
    return {
        "FIND_OBJECT":       "find_object",
        "DESCRIBE":          "describe",
        "NAVIGATE":          "navigate",
        "QUERY":             "query",
        "READ_HANDWRITING":  "read_handwriting",
        "MEMORY_QUERY":      "memory_node",
        "NAME_QUERY":        "name_node",
        "SAVE_LOCATION":     "save_location_node",
        "DELETE_LOCATION":   "delete_location_node",
        "SAVE_OBJECT":       "save_object_node",
        "SAVE_PERSON":       "save_person_node",
    }.get(state.get("mode", "IDLE"), "action_speak")


# ═══════════════════════════════════════════════════════════════
# NODE 4a — find_object (uses temporal consensus)
# ═══════════════════════════════════════════════════════════════

def find_object(state: GlassesState) -> GlassesState:
    target = state.get("find_target") or "object"
    scene  = state.get("scene") or {}
    cstate = scene.get("consensus_state", "SEARCHING")
    lang   = state.get("language", "en")
    rl     = state.get("rate_limited", False)

    # No frame yet → tell user we're opening the camera
    if not state.get("frame_b64"):
        return {**state,
                "speak": t("opening_camera_for_find", lang, target=target),
                "found": False}

    # Backend exhausted its free quota — stay silent (do NOT lie that
    # the camera is unclear).  The frontend will see rate_limited and
    # back off automatically.
    if rl:
        return {**state, "speak": "", "found": False}

    # Bad frame
    if scene.get("confidence") == "LOW" and cstate != "FOUND":
        return {**state,
                "speak": t("searching_camera_unclear", lang),
                "found": False}

    # FOUND (consensus reached)
    if cstate == "FOUND" and scene.get("target_found"):
        pos  = scene.get("target_position", "center")
        dist = scene.get("target_distance", "nearby") or "nearby"
        speak = t("found_target", lang,
                  target=target,
                  turn=turn_phrase(pos, lang),
                  dist=distance_phrase(dist, lang))
        # ── Auto-save to memory (silent, non-blocking) ──────────
        try:
            # Build a rich scene description from all available scene fields
            scene_parts = []
            env_raw   = scene.get("environment", "")
            stype_raw = scene.get("scene_type", "")
            if env_raw and env_raw != "unknown":
                scene_parts.append(env_raw)          # "indoor" / "outdoor"
            if stype_raw and stype_raw != "other":
                scene_parts.append(stype_raw)        # "room" / "desk" / "street"
            # Add nearby objects (excluding the found target itself)
            nearby = [
                o.get("label", "") for o in scene.get("objects", [])[:4]
                if o.get("label", "").lower() != target.lower()
                and o.get("distance") in ("close", "near", "medium")
            ]
            if nearby:
                scene_parts.append("near " + ", ".join(nearby))
            # Fallback to guidance text
            if not scene_parts:
                guidance = scene.get("guidance", "")
                if guidance:
                    scene_parts.append(guidance)
            scene_desc = ". ".join(scene_parts) if scene_parts else ""
            save_sighting(
                name              = target,
                lat               = state.get("user_lat"),
                lng               = state.get("user_lng"),
                scene_description = scene_desc,
                user_id           = state.get("user_id") or "",
            )
        except Exception as _me:
            print(f"[memory] auto-save error (non-fatal): {_me}")
        return {**state, "speak": speak, "found": True, "direction": pos}

    # SEARCHING — silent (don't repeat "still searching")
    if cstate == "SEARCHING":
        return {**state, "speak": "", "found": False}

    # NOT_FOUND after several attempts — give a directional hint
    objects = scene.get("objects", [])
    if objects:
        names = join_list([o["label"] for o in objects[:3]], lang)
        speak = t("cannot_see_with_others", lang, target=target, names=names)
        direction = "right"
    else:
        speak = t("cannot_see_alone", lang, target=target)
        direction = "right"
    return {**state, "speak": speak, "found": False, "direction": direction}


# ═══════════════════════════════════════════════════════════════
# NODE 4b — describe
# ═══════════════════════════════════════════════════════════════

def describe(state: GlassesState) -> GlassesState:
    scene = state.get("scene") or {}
    lang  = state.get("language", "en")
    has_frame = bool(state.get("frame_b64"))

    # No frame yet — this happens when /process is called for the
    # confirmation reply ("yes").  The camera screen is about to open
    # and will send a frame to /vision.  Stay silent so we don't say
    # "I cannot see clearly" right before the real description arrives.
    if not has_frame:
        return {**state, "speak": ""}

    if not scene or scene.get("confidence") == "LOW":
        return {**state, "speak": t("describe_unclear", lang)}

    env_raw    = scene.get("environment", "")
    stype_raw  = scene.get("scene_type", "")
    objects    = scene.get("objects", [])[:4]
    guidance   = scene.get("guidance", "")  # this comes from the VLM in EN
    if guidance and guidance.lstrip().startswith(('{', '[', '`')):
        guidance = ""

    # ── Enrich object labels with personal names from DB ────────
    _uid = state.get("user_id", "")
    if _uid:
        try:
            from memory_service import get_all_personal_objects
            _pers_objs = get_all_personal_objects(_uid)
            if _pers_objs:
                for obj in objects:
                    _lbl_words = set(obj.get("label", "").lower().split())
                    for po in _pers_objs:
                        _po_words = set(po["name"].lower().split())
                        if _lbl_words & _po_words:
                            obj["label"] = f"your {po['name']}"
                            break
        except Exception:
            pass

    parts = [t("object_phrase", lang,
               label=o["label"],
               position=position_word(o["position"], lang),
               dist=distance_phrase(o["distance"], lang))
             for o in objects]
    obj_text = join_list(parts, lang) if parts else t("describe_nothing_notable", lang)

    if env_raw and stype_raw and env_raw != "unknown":
        speak = t("describe_outdoor_indoor", lang,
                  env=env_word(env_raw, lang),
                  scene_type=scene_type_word(stype_raw, lang),
                  objects=obj_text,
                  guidance=guidance)
    else:
        speak = t("describe_simple", lang,
                  objects=obj_text,
                  guidance=guidance)
    speak = speak.strip()

    # ── Append emotion sentence (if any faces were classified) ──
    # We frame emotions cautiously: "looks happy" rather than
    # "is happy" — emotion classification on real-world faces is
    # noisy and a stranger's actual feelings are not ours to assert.
    emotions = state.get("emotions") or []
    if emotions:
        emo_parts = []
        # Cap at 2 most-confident faces to keep the sentence short
        for e in emotions[:2]:
            pos_key = f"face_position_{e['position']}"
            emo_parts.append(t("emotion_face_phrase", lang,
                               emotion=t(f"emotion_{e['label']}", lang),
                               position=t(pos_key, lang)))
        emo_sentence = join_list(emo_parts, lang)
        connector = " " if speak.endswith((".", "!", "?")) else ". "
        speak = speak + connector + emo_sentence
        if not speak.endswith((".", "!", "?")):
            speak += "."

    # ── Append identified-person sentence ───────────────────────
    # Only fires when person_id matched with at least medium confidence.
    _identified = scene.get("identified_persons") or []
    for _ip in _identified:
        if not _ip.get("match") or _ip.get("confidence") == "low":
            continue
        _name = _ip["match"]
        _rel  = (_ip.get("relationship") or "").strip().lower()
        _pos  = (_ip.get("position") or "center").lower()
        _connector = " " if speak.endswith((".", "!", "?")) else ". "

        # Special case: user saved their own face (relationship == "self")
        if _rel in {"self", "me", "myself"}:
            _i_see_you = {
                "en": f"I can see you, {_name}.",
                "fr": f"Je vous vois, {_name}.",
                "ar": f"أراك يا {_name}.",
                "tn": f"نشوفك يا {_name}.",
            }.get(lang, f"I can see you, {_name}.")
            speak = speak + _connector + _i_see_you
            continue

        _rel_prefix = {
            "en": f"{_rel} " if _rel else "",
            "fr": f"{_rel} " if _rel else "",
            "ar": f"({_rel}) " if _rel else "",
            "tn": f"({_rel}) " if _rel else "",
        }
        _rp = _rel_prefix.get(lang, _rel_prefix["en"])
        _person_phrases = {
            "en": {
                "left":   f"Your {_rp}{_name} is on your left.",
                "right":  f"Your {_rp}{_name} is on your right.",
                "center": f"Your {_rp}{_name} is right in front of you.",
            },
            "fr": {
                "left":   f"Votre {_rp}{_name} est à votre gauche.",
                "right":  f"Votre {_rp}{_name} est à votre droite.",
                "center": f"Votre {_rp}{_name} est juste devant vous.",
            },
            "ar": {
                "left":   f"{_name} {_rp}على يسارك.",
                "right":  f"{_name} {_rp}على يمينك.",
                "center": f"{_name} {_rp}أمامك مباشرة.",
            },
            "tn": {
                "left":   f"{_name} {_rp}في اليسار متاعك.",
                "right":  f"{_name} {_rp}في اليمين متاعك.",
                "center": f"{_name} {_rp}قدامك مباشرة.",
            },
        }
        _lang_map = _person_phrases.get(lang, _person_phrases["en"])
        _sentence  = _lang_map.get(_pos, _lang_map["center"])
        speak = speak + _connector + _sentence

    return {**state, "speak": speak}


# ═══════════════════════════════════════════════════════════════
# Reverse geocode helper (for "where am I")
# ═══════════════════════════════════════════════════════════════

def _reverse_geocode(lat: float, lng: float) -> Optional[str]:
    import requests as _req
    try:
        r = _req.get(
            "https://nominatim.openstreetmap.org/reverse",
            params={"lat": lat, "lon": lng, "format": "json"},
            headers={"User-Agent": "BlindGlassesApp/1.0"},
            timeout=8)
        addr = r.json().get("address", {})
        parts = []
        road = (addr.get("road") or addr.get("pedestrian")
                or addr.get("footway"))
        if road:
            parts.append(road)
        area = (addr.get("suburb") or addr.get("neighbourhood")
                or addr.get("city_district") or addr.get("town")
                or addr.get("city") or addr.get("county"))
        if area:
            parts.append(area)
        return ", ".join(parts) if parts else r.json().get("display_name", "")[:60]
    except Exception as e:
        print(f"[navigate] reverse geocode: {e}")
        return None


