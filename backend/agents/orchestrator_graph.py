# NODE 4c — navigate
# ═══════════════════════════════════════════════════════════════

def navigate(state: GlassesState, *, navigator: NavigateAgent) -> GlassesState:
    lat        = state.get("user_lat")
    lng        = state.get("user_lng")
    dest       = state.get("nav_destination")
    mode       = state.get("nav_mode") or "walking"
    lang       = state.get("language", "en")
    transcript = state.get("transcription", "").lower()

    if lat is None or lng is None:
        return {**state, "speak":
                "I need your GPS location to navigate. Please enable location."}

    # "Where am I?"
    if not dest and any(p in transcript for p in _LOCATION_PHRASES):
        area = _reverse_geocode(lat, lng)
        speak = (f"You are at {area}." if area
                 else f"Coordinates {lat:.5f} North, {lng:.5f} East.")
        return {**state, "speak": speak, "nav_update": None}

    # New trip (or different destination)
    if dest and (not navigator.has_active_trip
                 or dest.lower() != navigator.destination_str.lower()):
        # Check if dest is a saved named location — use its GPS directly
        dest_lat = None
        dest_lng = None
        try:
            from memory_service import get_named_location as _get_loc
            _saved = _get_loc(dest, state.get("user_id") or "")
            if _saved:
                dest_lat = _saved["gps_lat"]
                dest_lng = _saved["gps_lng"]
                print(f"[navigate] resolved '{dest}' → {dest_lat},{dest_lng}")
                # Check if user is already at this location (within ~50m)
                if lat is not None and lng is not None:
                    _dlat = abs(dest_lat - lat)
                    _dlng = abs(dest_lng - lng)
                    if _dlat < 0.0005 and _dlng < 0.0005:  # ~50m
                        _already_there = {
                            "en": f"You are already at {dest}.",
                            "fr": f"Vous êtes déjà à {dest}.",
                            "ar": f"أنت بالفعل في {dest}.",
                            "tn": f"انت توا في {dest}.",
                        }
                        return {**state,
                                "speak": _already_there.get(lang, _already_there["en"]),
                                "nav_update": None}
                dest = f"{dest_lat},{dest_lng}"
        except Exception:
            pass
        result = navigator.start_trip(origin_lat=lat, origin_lng=lng,
                                      destination=dest, mode=mode,
                                      language=lang)
        nav_update = {"arrived": False, "off_route": False,
                      "detour_warning": None, "current_step": 0}
        return {**state, "speak": result["speak"],
                "nav_update": nav_update, "direction": "center"}

    # Recalculate
    if "recalculate" in transcript or "reroute" in transcript:
        result = navigator.recalculate(lat, lng)
        return {**state, "speak": result["speak"], "direction": "center"}

    # Regular GPS update
    if navigator.has_active_trip:
        update    = navigator.update_position(lat, lng)
        speak     = update.get("speak", "")
        interrupt = bool(update.get("detour_warning"))
        return {**state, "speak": speak, "interrupt": interrupt,
                "nav_update": update, "direction": "center"}

    return {**state, "speak":
            "Where would you like to go? Say take me to followed by a place."}


