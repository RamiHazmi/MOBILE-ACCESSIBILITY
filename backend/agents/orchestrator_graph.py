def build_graph(api_key: str, google_api_key: str = "",
                emotion_agent=None):
    perception_agent = PerceptionAgent(
        api_key=api_key, mode="external",
        primary_model=VLM_MODEL_VISION,
        fallback_model=VLM_MODEL_FALLBACK,
        extra_fallbacks=VLM_MODEL_EXTRA_FALLBACKS,
        google_api_key=google_api_key,
        min_confirmations=VISION_MIN_CONFIRMATIONS,
        history_size=VISION_MAX_HISTORY,
    )
    action_agent   = ActionAgent()
    navigate_agent = NavigateAgent()

    def _perception(s):   return perception_node(s, perception=perception_agent,
                                                  emotion=emotion_agent)
    def _action_speak(s): return action_speak(s, action=action_agent)
    def _navigate(s):     return navigate(s, navigator=navigate_agent)

    g = StateGraph(GlassesState)
    g.add_node("perception",   _perception)
    g.add_node("danger_node",  danger_node)
    g.add_node("confirm_node", confirm_node)
    g.add_node("clarify_node", clarify_node)
    g.add_node("route_intent", route_intent)
    g.add_node("find_object",  find_object)
    g.add_node("describe",     describe)
    g.add_node("navigate",     _navigate)
    g.add_node("query",             query)
    g.add_node("read_handwriting",  read_handwriting_node)
